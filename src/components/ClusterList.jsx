import { useState } from 'react';

function fmtRs(n) {
  if (n >= 100000) return `₹${(n / 100000).toFixed(2)} L`;
  return `₹${Math.round(n).toLocaleString('en-IN')}`;
}

function fmtDate(s) {
  if (!s) return '—';
  const d = new Date(s);
  return d.toLocaleDateString('en-IN', { day: 'numeric', month: 'short', year: 'numeric' });
}

// ─── Cluster card ─────────────────────────────────────────────────────────────

function ClusterCard({ cluster, plan, idx, onFocus }) {
  const [copied, setCopied] = useState(false);

  const agencies = [...new Set(cluster.map((w) => w.agency))].join(', ');
  const streets = [...new Set(cluster.flatMap((w) => w.segments ?? []))].join(', ');
  const originalStarts = cluster.map((w) => `${w.agency}: ${fmtDate(w.startDate)}`).join(' | ');

  const sharedEnd = (() => {
    const d = new Date(plan.sharedStart);
    d.setDate(d.getDate() + plan.sharedDuration);
    return d.toISOString().slice(0, 10);
  })();

  const copyMemo = () => {
    const lines = [
      `COORDINATION MEMO — DigOnce`,
      `────────────────────────────`,
      `Cluster ${idx + 1}: ${agencies}`,
      `Streets: ${streets}`,
      ``,
      `Individual schedules:`,
      ...cluster.map((w) => `  • ${w.agency} (${w.workType}): ${fmtDate(w.startDate)}, ${w.durationDays} days`),
      ``,
      `Proposed shared window: ${fmtDate(plan.sharedStart)} → ${fmtDate(sharedEnd)} (${plan.sharedDuration} days)`,
      ``,
      `Estimated savings:`,
      `  Restoration cost avoided: ${fmtRs(plan.savingsRs)}`,
      `  Disruption days saved: ${plan.daysSaved}`,
      ``,
      plan.formulaText,
      ``,
      ...(plan.piggyback?.length > 0
        ? ['PIGGYBACK ALERTS:', ...plan.piggyback.map((p) => `  🔔 ${p.text}`), '']
        : []),
      `Please coordinate with all agencies to align on the shared window.`,
      `Generated by DigOnce — One trench. One repair. One disruption.`,
    ];
    navigator.clipboard.writeText(lines.join('\n')).then(() => {
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    });
  };

  return (
    <div
      className="card"
      style={{ marginBottom: 12, cursor: 'pointer', transition: 'border-color 0.2s' }}
      onMouseEnter={(e) => { e.currentTarget.style.borderColor = '#ef4444'; }}
      onMouseLeave={(e) => { e.currentTarget.style.borderColor = '#334155'; }}
      onClick={() => onFocus?.(cluster[0])}
    >
      {/* Header */}
      <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start', marginBottom: 8 }}>
        <div>
          <div style={{ fontWeight: 700, fontSize: 14, marginBottom: 2 }}>
            Cluster {idx + 1}: {agencies}
          </div>
          <div style={{ fontSize: 12, color: '#94a3b8' }}>📍 {streets}</div>
        </div>
        {plan.hasEmergency && (
          <span style={{
            background: '#7f1d1d', color: '#fca5a5', borderRadius: 4,
            padding: '2px 8px', fontSize: 11, fontWeight: 700, whiteSpace: 'nowrap',
          }}>
            🚨 Emergency
          </span>
        )}
      </div>

      {/* Schedule */}
      <div style={{ fontSize: 12, color: '#cbd5e1', marginBottom: 8 }}>
        <span style={{ color: '#94a3b8' }}>Original: </span>{originalStarts}
        <span style={{ color: '#94a3b8', marginLeft: 8 }}>→</span>
        <span style={{ color: '#4ade80', marginLeft: 8, fontWeight: 600 }}>
          Shared: {fmtDate(plan.sharedStart)} – {fmtDate(sharedEnd)} ({plan.sharedDuration} days)
        </span>
      </div>

      {/* Big numbers */}
      <div style={{ display: 'flex', gap: 20, marginBottom: 8 }}>
        <div>
          <div className="stat-big" style={{ color: '#4ade80' }}>{fmtRs(plan.savingsRs)}</div>
          <div className="stat-label">restoration cost avoided</div>
        </div>
        <div>
          <div className="stat-big" style={{ color: '#38bdf8' }}>{plan.daysSaved}</div>
          <div className="stat-label">disruption-days saved</div>
        </div>
      </div>

      {/* Formula */}
      <div style={{
        fontFamily: 'monospace', fontSize: 10, color: '#64748b',
        background: '#0f172a', borderRadius: 6, padding: '6px 8px', marginBottom: 8,
        whiteSpace: 'pre-wrap',
      }}>
        {plan.formulaText}
      </div>

      {/* Piggyback */}
      {plan.piggyback?.length > 0 && (
        <div style={{
          background: '#1c0606', border: '1px solid #7f1d1d',
          borderRadius: 6, padding: '8px 10px', marginBottom: 8,
        }}>
          <div style={{ fontWeight: 700, fontSize: 11, color: '#f87171', marginBottom: 4 }}>
            🔔 PIGGYBACK ALERTS
          </div>
          {plan.piggyback.map((p) => (
            <div key={p.workId} style={{ fontSize: 12, color: '#fca5a5', marginBottom: 2 }}>
              {p.agency}: {p.text}
            </div>
          ))}
        </div>
      )}

      {/* Copy memo */}
      <button
        className="btn btn-secondary btn-sm"
        onClick={(e) => { e.stopPropagation(); copyMemo(); }}
        type="button"
        id={`copy-memo-${idx}`}
      >
        {copied ? '✓ Copied!' : '📋 Copy coordination memo'}
      </button>
    </div>
  );
}

// ─── Fresh-road alert card ────────────────────────────────────────────────────

function FreshRoadCard({ alert, config, onFocus, works }) {
  const work = works.find((w) => w.id === alert.workId);
  return (
    <div
      className="card"
      style={{
        marginBottom: 10, borderColor: '#ea580c', cursor: 'pointer',
        transition: 'border-color 0.2s',
      }}
      onMouseEnter={(e) => { e.currentTarget.style.borderColor = '#f97316'; }}
      onMouseLeave={(e) => { e.currentTarget.style.borderColor = '#ea580c'; }}
      onClick={() => work && onFocus?.(work)}
    >
      <div style={{ display: 'flex', alignItems: 'center', gap: 8, marginBottom: 6 }}>
        <span style={{ fontSize: 18 }}>🟠</span>
        <span style={{ fontWeight: 700, fontSize: 13 }}>Fresh-Road Guard</span>
        <span style={{
          background: '#7c2d12', color: '#fb923c', borderRadius: 4,
          padding: '1px 6px', fontSize: 11, fontWeight: 700,
        }}>
          {alert.agency}
        </span>
      </div>
      <div style={{ fontSize: 13, marginBottom: 4 }}>
        <strong>{alert.street}</strong> was resurfaced{' '}
        <strong style={{ color: '#fb923c' }}>{alert.monthsSince} months ago</strong> — this cut breaks
        the {config.protectionMonths}-month protection.
      </div>
      <div style={{ fontSize: 11, color: '#94a3b8', fontStyle: 'italic', marginBottom: 2 }}>
        (assumption, not official rate)
      </div>
      <div style={{ fontSize: 13, color: '#fcd34d' }}>
        Est. restoration cost: <strong>{fmtRs(alert.estCostRs)}</strong>
      </div>
      <div style={{ fontSize: 12, color: '#94a3b8', marginTop: 2 }}>
        Responsible agency: <strong>{alert.agency}</strong>
      </div>
    </div>
  );
}

// ─── Main ClusterList ─────────────────────────────────────────────────────────

export default function ClusterList({ clusters, plans, freshAlerts, works, config, onFocus }) {
  return (
    <div>
      {/* Conflict clusters */}
      <div className="section-title">
        <span>⚠</span> Conflicts ({clusters.length})
      </div>

      {clusters.length === 0 && (
        <div style={{ color: '#64748b', fontSize: 13, padding: '12px 0' }}>
          No overlapping works detected yet. Add more notices using the Intake above.
        </div>
      )}

      {clusters.map((cluster, idx) => (
        <ClusterCard
          key={`cluster-${idx}`}
          cluster={cluster}
          plan={plans[idx]}
          idx={idx}
          onFocus={onFocus}
        />
      ))}

      {/* Fresh-road alerts */}
      {freshAlerts.length > 0 && (
        <>
          <div className="section-title" style={{ marginTop: 20 }}>
            <span>🟠</span> Fresh-Road Guard ({freshAlerts.length})
          </div>
          {freshAlerts.map((alert, i) => (
            <FreshRoadCard
              key={`fresh-${i}`}
              alert={alert}
              config={config}
              onFocus={onFocus}
              works={works}
            />
          ))}
        </>
      )}
    </div>
  );
}
